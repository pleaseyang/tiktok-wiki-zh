def process_directory(base_dir, sub_dir, specific_translations_map):
    """Process all files in a directory."""
    dir_path = os.path.join(base_dir, sub_dir)
    count = 0
    
    for fname in os.listdir(dir_path):
        if not fname.endswith('.md'):
            continue
        
        filepath = os.path.join(dir_path, fname)
        specific = specific_translations_map.get(fname, {})
        
        translate_file(filepath, specific if specific else None)
        count += 1
        print(f"  Translated: {fname}")
    
    return count


