def translate_file(filepath, specific_translations=None):
    """Read file, apply translations, write back."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Apply specific translations first (more precise)
    if specific_translations:
        for eng, chn in specific_translations.items():
            content = content.replace(eng, chn)
    
    # Apply common translations
    content = translate_content(content)
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return True


